/**
 * Icon set traced from the ByteSpace Figma file.
 * Every icon uses `currentColor`, so its colour is set with a Tailwind text class,
 * e.g. <StarIcon className="h-4 w-4 text-lime" />. Icons are decorative by default
 * (aria-hidden); pass a `title` when the icon is the only content of a control.
 */

function createIcon(viewBox, paths) {
  function Icon({ className = 'h-5 w-5', title, ...props }) {
    return (
      <svg
        viewBox={viewBox}
        fill="currentColor"
        className={className}
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden={title ? undefined : true}
        role={title ? 'img' : undefined}
        focusable="false"
        {...props}
      >
        {title && <title>{title}</title>}
        {paths.map(([d, evenOdd], index) => (
          // Paths never reorder, so the index is a stable key.
          <path key={index} d={d} fillRule={evenOdd ? 'evenodd' : undefined} />
        ))}
      </svg>
    );
  }
  return Icon;
}

